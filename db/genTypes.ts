import type { DatabaseSync } from "node:sqlite";
import { columnsOf, type Column } from "../server/db";

// Writes src/lib/database.types.ts in the same shape as `supabase gen types`,
// so hooks/queries.ts can use Tables<"x"> / TablesInsert<"x"> /
// TablesUpdate<"x"> exactly as the admin does.

type Relation = { name: string; type: "table" | "view" };

const HEADER = `// Generated by \`pnpm db:types\` (also run by \`pnpm db:migrate\`) from the
// migrated schema. Don't edit by hand.

export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[];
`;

const HELPERS = `
type PublicSchema = Database["public"];

export type TableName = keyof PublicSchema["Tables"];
export type ViewName = keyof PublicSchema["Views"];

export type Tables<T extends TableName | ViewName> =
  T extends TableName
    ? PublicSchema["Tables"][T]["Row"]
    : T extends ViewName
      ? PublicSchema["Views"][T]["Row"]
      : never;

export type TablesInsert<T extends TableName> =
  PublicSchema["Tables"][T]["Insert"];

export type TablesUpdate<T extends TableName> =
  PublicSchema["Tables"][T]["Update"];
`;

// By declared type; view columns computed without a cast have none, so cast
// them in the view (`cast(count(*) as integer) as try_count`).
function tsType(column: Column): string {
  const type = column.type;
  if (type === "boolean") return "boolean";
  if (type === "json") return "Json";
  if (/int|real|floa|doub|num|dec/.test(type)) return "number";
  if (/char|clob|text|date|time/.test(type)) return "string";
  return "unknown";
}

function rowType(column: Column, isView: boolean): string {
  const nullable = isView || !(column.notNull || column.pk);
  return `${tsType(column)}${nullable ? " | null" : ""}`;
}

function block(
  label: string,
  columns: Column[],
  field: (column: Column) => string,
  indent: string,
): string {
  const lines = columns.map((column) => `${indent}  ${field(column)};`);
  return `${indent}${label}: {\n${lines.join("\n")}\n${indent}};`;
}

function relationType(db: DatabaseSync, relation: Relation): string {
  const columns = columnsOf(db, relation.name);
  const isView = relation.type === "view";
  const indent = "        ";
  const parts = [
    block("Row", columns, (c) => `${c.name}: ${rowType(c, isView)}`, indent),
  ];
  if (!isView) {
    parts.push(
      block(
        "Insert",
        columns,
        (c) =>
          c.pk
            ? `${c.name}?: never`
            : `${c.name}${!c.notNull || c.hasDefault ? "?" : ""}: ${rowType(c, false)}`,
        indent,
      ),
      block(
        "Update",
        columns,
        (c) => (c.pk ? `${c.name}?: never` : `${c.name}?: ${rowType(c, false)}`),
        indent,
      ),
    );
  }
  return `      ${relation.name}: {\n${parts.join("\n")}\n      };`;
}

function section(db: DatabaseSync, label: string, relations: Relation[]) {
  const body = relations.length
    ? relations.map((relation) => relationType(db, relation)).join("\n")
    : "      [_ in never]: never;";
  return `    ${label}: {\n${body}\n    };`;
}

export function generateTypes(db: DatabaseSync): string {
  const relations = db
    .prepare(
      `select name, type from sqlite_schema
       where type in ('table', 'view')
         and name not like 'sqlite_%'
         and name <> 'schema_migrations'
       order by name`,
    )
    .all() as Relation[];

  const tables = relations.filter((relation) => relation.type === "table");
  const views = relations.filter((relation) => relation.type === "view");

  return `${HEADER}
export type Database = {
  public: {
${section(db, "Tables", tables)}
${section(db, "Views", views)}
  };
};
${HELPERS}`;
}
